def normalize_language(language: str | None) -> str:
    code = (language or "").strip().lower()
    return code if code in SUPPORTED_LANGUAGES else "en"


def urgency_label(language: str | None, code: str) -> str:
    lang = normalize_language(language)
    if lang == "en":
        return ENGLISH_URGENCY.get(code, ENGLISH_URGENCY["consult"])
    return _MESSAGES[lang].get(_URGENCY_KEYS.get(code, "urgency_consult"))


def localize_result(result: TriageResult, language: str | None) -> TriageResult:
    lang = normalize_language(language)
    if lang == "en":
        return result

    pack = _MESSAGES[lang]
    summary_key = _SUMMARY_KEYS.get(result.summary, "summary_consult")
    advice_key = _ADVICE_KEYS.get(result.urgency_code, "advice_consult")
    red_flag_map = pack["red_flags"]

    return TriageResult(
        urgency=result.urgency,
        summary=pack[summary_key],
        advice=tuple(pack[advice_key]),
        red_flags=tuple(red_flag_map.get(flag, flag) for flag in result.red_flags),
        emergency=result.emergency,
        engine=result.engine,
        disclaimer=pack["disclaimer"],
    )
